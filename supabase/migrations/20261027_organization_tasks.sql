-- Persistent organization task history.
-- Apply this migration to the existing Tambala MCP Supabase database.
-- Financial data is intentionally not stored here; this table tracks orchestration state only.

create table if not exists public.organization_tasks (
  id text primary key,
  objective text not null,
  status text not null check (status in ('created','ceo_analyzing','delegated','executing','waiting_for_tool','department_review','returned_to_ceo','needs_more_work','completed','failed')),
  current_stage text not null check (current_stage in ('founder','ceo','department','review','complete','failed')),
  assigned_department_id text null,
  assigned_role_id text null,
  research_query text null,
  result jsonb null,
  error_message text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz null
);

create index if not exists organization_tasks_status_idx on public.organization_tasks(status);
create index if not exists organization_tasks_created_at_idx on public.organization_tasks(created_at desc);
create index if not exists organization_tasks_department_idx on public.organization_tasks(assigned_department_id);

create table if not exists public.organization_task_events (
  id bigint generated by default as identity primary key,
  task_id text not null references public.organization_tasks(id) on delete cascade,
  event_type text not null,
  stage text not null,
  actor_role_id text null,
  department_id text null,
  payload jsonb null,
  created_at timestamptz not null default now()
);

create index if not exists organization_task_events_task_idx on public.organization_task_events(task_id, created_at);

-- The server uses the Supabase service-role key for these writes. Do not expose
-- service-role credentials to browser clients.
comment on table public.organization_tasks is 'Persistent orchestration state for Founder -> CEO -> department workflows.';
comment on table public.organization_task_events is 'Append-only execution history for organization tasks.';
