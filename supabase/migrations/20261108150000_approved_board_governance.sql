-- Approved internal AI advisory Board governance records.
-- The Board may deliberate and recommend; only the Founder may resolve reserved matters.
begin;

create table if not exists public.organization_board_members (
  id uuid primary key default gen_random_uuid(),
  role_id text not null unique references public.organization_roles(id) on delete restrict,
  seat_title text not null,
  member_type text not null check (member_type in ('founder_chair', 'advisory_member', 'board_secretary', 'executive_observer')),
  active boolean not null default true,
  voting_rights boolean not null default false check (voting_rights = false),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_board_meetings (
  id uuid primary key default gen_random_uuid(),
  meeting_number bigint generated by default as identity unique,
  title text not null,
  meeting_type text not null default 'ordinary' check (meeting_type in ('ordinary', 'strategic_review', 'special', 'inaugural')),
  status text not null default 'scheduled' check (status in ('scheduled', 'in_session', 'completed', 'cancelled')),
  scheduled_at timestamptz,
  opened_at timestamptz,
  closed_at timestamptz,
  chair_role_id text not null default 'founder' references public.organization_roles(id) on delete restrict,
  secretary_role_id text references public.organization_roles(id) on delete restrict,
  created_by_role_id text not null default 'founder' references public.organization_roles(id) on delete restrict,
  purpose text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (chair_role_id = 'founder'),
  check (created_by_role_id = 'founder')
);

create table if not exists public.organization_board_attendance (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null references public.organization_board_meetings(id) on delete cascade,
  role_id text not null references public.organization_roles(id) on delete restrict,
  attendance_status text not null default 'invited' check (attendance_status in ('invited', 'present', 'absent', 'apology', 'observer')),
  seat_title text not null,
  recorded_at timestamptz not null default now(),
  unique (meeting_id, role_id)
);

create table if not exists public.organization_board_agenda_items (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null references public.organization_board_meetings(id) on delete cascade,
  item_number integer not null,
  title text not null,
  background text not null default '',
  presenter_role_id text references public.organization_roles(id) on delete restrict,
  status text not null default 'pending' check (status in ('pending', 'discussed', 'deferred')),
  created_at timestamptz not null default now(),
  unique (meeting_id, item_number)
);

create table if not exists public.organization_board_minutes (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null unique references public.organization_board_meetings(id) on delete cascade,
  summary text not null default '',
  discussion_notes jsonb not null default '[]'::jsonb,
  evidence_refs jsonb not null default '[]'::jsonb,
  prepared_by_role_id text not null default 'director-board-governance' references public.organization_roles(id) on delete restrict,
  reviewed_by_role_id text references public.organization_roles(id) on delete restrict,
  founder_confirmed_at timestamptz,
  founder_confirmed_by_role_id text references public.organization_roles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (founder_confirmed_by_role_id is null or founder_confirmed_by_role_id = 'founder')
);

create table if not exists public.organization_board_recommendations (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null references public.organization_board_meetings(id) on delete cascade,
  agenda_item_id uuid references public.organization_board_agenda_items(id) on delete set null,
  title text not null,
  recommendation text not null,
  rationale text not null default '',
  risk_level text not null default 'medium' check (risk_level in ('low', 'medium', 'high', 'critical')),
  status text not null default 'submitted' check (status in ('submitted', 'founder_accepted', 'founder_rejected', 'deferred', 'implemented')),
  founder_decision_note text,
  founder_decided_at timestamptz,
  founder_decided_by_role_id text references public.organization_roles(id) on delete restrict,
  proposed_by_role_id text not null references public.organization_roles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (founder_decided_by_role_id is null or founder_decided_by_role_id = 'founder'),
  check (status = 'submitted' or founder_decided_by_role_id = 'founder')
);

create table if not exists public.organization_board_actions (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null references public.organization_board_meetings(id) on delete cascade,
  recommendation_id uuid references public.organization_board_recommendations(id) on delete set null,
  title text not null,
  description text not null default '',
  assigned_role_id text not null references public.organization_roles(id) on delete restrict,
  due_at timestamptz,
  status text not null default 'open' check (status in ('open', 'in_progress', 'blocked', 'completed', 'cancelled')),
  completion_evidence text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists organization_board_meetings_status_idx on public.organization_board_meetings(status, scheduled_at desc);
create index if not exists organization_board_recommendations_status_idx on public.organization_board_recommendations(status, created_at desc);
create index if not exists organization_board_actions_status_idx on public.organization_board_actions(status, due_at);

alter table public.organization_board_members enable row level security;
alter table public.organization_board_meetings enable row level security;
alter table public.organization_board_attendance enable row level security;
alter table public.organization_board_agenda_items enable row level security;
alter table public.organization_board_minutes enable row level security;
alter table public.organization_board_recommendations enable row level security;
alter table public.organization_board_actions enable row level security;

-- Explicitly advisory membership. The Founder chairs; selected directors advise;
-- Board & Corporate Governance maintains records but has no approval power.
insert into public.organization_board_members (role_id, seat_title, member_type, active, voting_rights) values
  ('founder', 'Founder & Board Chair', 'founder_chair', true, false),
  ('director-finance-accounting', 'Finance & Risk Adviser', 'advisory_member', true, false),
  ('director-strategy-planning', 'Strategy & Corporate Planning Adviser', 'advisory_member', true, false),
  ('director-technology-engineering', 'Technology & Innovation Adviser', 'advisory_member', true, false),
  ('director-legal-risk-compliance', 'Governance, Legal & Compliance Adviser', 'advisory_member', true, false),
  ('director-board-governance', 'Board Secretary', 'board_secretary', true, false)
on conflict (role_id) do update set seat_title = excluded.seat_title, member_type = excluded.member_type, active = excluded.active, voting_rights = false, updated_at = now();

update public.organization_roles
set title = 'AI Advisory Board',
    purpose = 'Provide strategic oversight, challenge assumptions, review performance and risk, and submit non-binding recommendations to the Founder. The Board has no independent approval or execution authority.',
    capabilities = array_remove(coalesce(capabilities, array[]::text[]), 'approvals.resolve_board'),
    updated_at = now()
where id = 'board';

commit();
