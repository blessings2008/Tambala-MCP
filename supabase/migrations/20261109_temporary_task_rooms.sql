-- Durable, isolated workspaces for every staff handoff.
-- "Temporary" means the active room is closed after review; its history is retained.

create table if not exists public.organization_task_rooms (
  id uuid primary key default gen_random_uuid(),
  handoff_id uuid not null unique references public.organization_handoffs(id) on delete cascade,
  parent_task_id text null,
  owner_role_id text not null references public.organization_roles(id) on delete restrict,
  owner_agent text not null,
  opened_by_role_id text not null references public.organization_roles(id) on delete restrict,
  objective text not null check (char_length(objective) between 5 and 1000),
  context_packet jsonb not null default '{}'::jsonb,
  status text not null default 'active' check (status in ('active','awaiting_founder','blocked','ready_for_review','revision_requested','completed','failed','cancelled','archived')),
  deliverable text null,
  blocker text null,
  opened_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  closed_at timestamptz null
);
create index if not exists organization_task_rooms_status_idx on public.organization_task_rooms(status, updated_at desc);
create index if not exists organization_task_rooms_parent_idx on public.organization_task_rooms(parent_task_id);
create table if not exists public.organization_task_room_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.organization_task_rooms(id) on delete cascade,
  event_type text not null,
  actor_role_id text null,
  payload jsonb null,
  created_at timestamptz not null default now()
);
create index if not exists organization_task_room_events_room_idx on public.organization_task_room_events(room_id, created_at);
alter table public.organization_task_rooms enable row level security;
alter table public.organization_task_room_events enable row level security;
revoke all on public.organization_task_rooms from anon, authenticated;
revoke all on public.organization_task_room_events from anon, authenticated;

alter table public.organization_handoffs
  add column if not exists room_id uuid null references public.organization_task_rooms(id) on delete set null;
alter table public.organization_handoffs drop constraint if exists organization_handoffs_status_check;
alter table public.organization_handoffs add constraint organization_handoffs_status_check
  check (status in ('queued','running','awaiting_founder','completed','failed'));

-- Allow an executing task to pause for human input without falsely completing it.
alter table public.organization_tasks drop constraint if exists organization_tasks_status_check;
alter table public.organization_tasks add constraint organization_tasks_status_check
  check (status in ('created','ceo_analyzing','delegated','executing','waiting_for_tool','department_review','returned_to_ceo','needs_more_work','completed','failed'));
