// Generates SQL that loads the seed organization and the optional activation script.
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { initialOrganization } from '../src/organization/seed.ts';
import { DEPARTMENT_CAPABILITIES, routeObjective } from '../src/organization/capability-registry.ts';

const q = (v: string | null) => (v === null ? 'null' : `'${v.replaceAll("'", "''")}'`);
const arr = (v: string[]) => `array[${v.map((x) => q(x)).join(',')}]::text[]`;
const { units, roles } = initialOrganization;

// Parents first so the self-reference holds.
const orderedUnits = [...units].sort((a, b) => Number(a.parentId !== null) - Number(b.parentId !== null));
let seed = '-- Generated by `npm run seed:sql` from src/organization/seed.ts. Idempotent; never overwrites existing rows.\n\n';
seed += 'insert into public.organization_units (id,name,kind,parent_id,purpose,status,accountable_role_ids,tags) values\n';
seed += orderedUnits.map((u) => `(${q(u.id)},${q(u.name)},${q(u.kind)},${q(u.parentId)},${q(u.purpose)},${q(u.status)},${arr(u.accountableRoleIds)},${arr(u.tags)})`).join(',\n');
seed += '\non conflict (id) do nothing;\n\n';

// Roles reference each other and their unit; insert with null reports_to, then link.
seed += 'insert into public.organization_roles (id,title,kind,unit_id,reports_to_role_id,purpose,capabilities,activation) values\n';
seed += roles.map((r) => `(${q(r.id)},${q(r.title)},${q(r.kind)},${q(r.unitId)},null,${q(r.purpose)},${arr(r.capabilities)},${q(r.activation)})`).join(',\n');
seed += '\non conflict (id) do nothing;\n\n';
for (const r of roles.filter((x) => x.reportsToRoleId)) {
  seed += `update public.organization_roles set reports_to_role_id=${q(r.reportsToRoleId)} where id=${q(r.id)} and reports_to_role_id is null;\n`;
}
writeFileSync('supabase/migrations/20261028_organization_seed.sql', seed);

// Activation is an organizational decision, so it is NOT a migration. Run it deliberately.
const executorRoles = new Set<string>();
for (const cap of DEPARTMENT_CAPABILITIES) {
  const m = routeObjective(initialOrganization, cap.objectiveKeywords[0]).find((x) => x.capability.id === cap.id);
  if (m?.role) executorRoles.add(m.role.id);
}
const ids = ['ceo', ...executorRoles];
let act = '-- Activates the CEO and the 18 department/business-unit leads that have execution agents.\n';
act += '-- Review first: execution only works for ACTIVE roles. Run in the Supabase SQL editor.\n';
act += `update public.organization_roles set activation='active', updated_at=now() where id in (${ids.map((i) => q(i)).join(',')});\n`;
act += `-- Roll back: update public.organization_roles set activation='planned' where id in (${ids.map((i) => q(i)).join(',')});\n`;
writeFileSync('supabase/manual/activate_agent_roles.sql', act);

const bind = `-- Bind your connection to the Founder role so write tools work with TAMBALA_ENFORCE_ROLE_BINDINGS=true.
-- Find your OAuth client id by calling the MCP tool get_my_organization_identity (it reports the denial with the client id in the audit log),
-- or read it from organization_audit_events (target_type='oauth_client').
insert into public.organization_actor_bindings (principal_type, principal_id, role_id, note)
values ('oauth_client', '<PASTE_OAUTH_CLIENT_ID>', 'founder', 'Founder connection');
`;
writeFileSync('supabase/manual/bind_founder.sql', bind);
console.log(`Wrote seed (${units.length} units, ${roles.length} roles) and activation for ${ids.length} roles.`);
